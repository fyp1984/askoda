-- POC B 库（零售/会员域）模拟数据 · 2026-09-28
-- 依据：PRD §17.3 八张核心表（可见字段数与 PRD 一致，敏感字段建表不建模）
-- 用途：POC 双库回放（题库 30 题 + 陷阱 10 例），数据为确定性模拟数据
-- =====================================================================

-- ---------- 门店维表（可见 5 字段；region 枚举刻意不含"西南大区"，陷阱 #8） ----------
CREATE TABLE dim_store (
    store_id     INT PRIMARY KEY,
    store_name   VARCHAR(50) NOT NULL,
    region_name  VARCHAR(20) NOT NULL,   -- 枚举：华东大区/华北大区/华南大区
    store_type   VARCHAR(10) NOT NULL,   -- 枚举：直营/加盟
    open_date    DATE NOT NULL
);

-- ---------- 会员维表（MDL 可见 6 字段；手机号/证件号建表但【不建模】，陷阱 #1/#9） ----------
CREATE TABLE dim_member (
    member_id     INT PRIMARY KEY,
    member_name   VARCHAR(30) NOT NULL,
    grade         VARCHAR(10) NOT NULL,  -- 枚举：普通/银卡/金卡/钻石
    member_status VARCHAR(10) NOT NULL,  -- 枚举：活跃/沉默/流失
    register_date DATE NOT NULL,
    store_id      INT REFERENCES dim_store(store_id),  -- 归属门店
    member_phone  VARCHAR(20),           -- 敏感：AI 不可见
    id_card       VARCHAR(30)            -- 敏感：AI 不可见
);

-- ---------- 订单明细（可见 6 字段；load_time 建表不建模，陷阱 #6） ----------
CREATE TABLE dwd_order_di (
    order_id     INT PRIMARY KEY,
    member_id    INT REFERENCES dim_member(member_id),
    store_id     INT REFERENCES dim_store(store_id),
    pay_amount   NUMERIC(10,2) NOT NULL,
    order_date   DATE NOT NULL,          -- 业务日期
    order_status VARCHAR(10) NOT NULL,   -- 枚举：已完成/已退款
    load_time    TIMESTAMP DEFAULT now() -- 装载时间：非业务日期，AI 不可见
);

-- ---------- 订单明细扩展（可见 8 字段；口径：订单金额=SUM(sales_amount) 不含退款） ----------
CREATE TABLE dwd_order_detail_di (
    detail_id     INT PRIMARY KEY,
    order_id      INT REFERENCES dwd_order_di(order_id),
    store_id      INT REFERENCES dim_store(store_id),
    sku_id        INT NOT NULL,
    category_name VARCHAR(20) NOT NULL,  -- 维度退化列
    quantity      INT NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    sales_amount  NUMERIC(10,2) NOT NULL
);

-- ---------- 门店日汇总（可见 7 字段；口径：日均销售额=AVG(sales_amount)，坪效=sales/area） ----------
CREATE TABLE dws_store_daily_agg (
    stat_date    DATE NOT NULL,
    store_id     INT REFERENCES dim_store(store_id),
    sales_amount NUMERIC(12,2) NOT NULL,
    order_cnt    INT NOT NULL,
    member_cnt   INT NOT NULL,
    area_sqm     NUMERIC(8,2) NOT NULL,
    day_type     VARCHAR(10) NOT NULL,   -- 枚举：工作日/周末/节假日
    PRIMARY KEY (stat_date, store_id)
);

-- ---------- 券核销（可见 6 字段；核销GMV/券成本口径【待上架】，陷阱 #2/#3；与订单表无建模关系，陷阱 #7） ----------
CREATE TABLE ads_coupon_order_di (
    coupon_order_id INT PRIMARY KEY,
    member_id       INT REFERENCES dim_member(member_id),
    coupon_type     VARCHAR(10) NOT NULL, -- 枚举：满减券/折扣券/新人券
    coupon_amount   NUMERIC(10,2) NOT NULL,
    order_gmv       NUMERIC(12,2) NOT NULL,
    stat_date       DATE NOT NULL
);

-- ---------- 等级异动（可见 4 字段） ----------
CREATE TABLE ads_member_grade_change_wi (
    change_id   INT PRIMARY KEY,
    member_id   INT REFERENCES dim_member(member_id),
    change_month DATE NOT NULL,
    change_type VARCHAR(10) NOT NULL     -- 枚举：升级/降级
);

-- ---------- 复购汇总（可见 5 字段；口径：复购用户数=SUM(repurchase_flag)，复购率=复购用户数/活跃用户数） ----------
CREATE TABLE ads_member_repurchase_di (
    member_id       INT REFERENCES dim_member(member_id),
    store_id        INT REFERENCES dim_store(store_id),
    stat_month      DATE NOT NULL,       -- 月粒度
    repurchase_flag INT NOT NULL,        -- 0/1
    order_cnt       INT NOT NULL,
    PRIMARY KEY (member_id, stat_month)
);

